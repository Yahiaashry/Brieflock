function doc(
  input: Omit<
    DocumentRecord,
    "mime_type" | "sha256" | "scan_method" | "superseded" | "storage_path"
  >,
): DocumentRecord {
  return {
    ...input,
    mime_type: "application/pdf",
    scan_method: "magic-bytes-mvp",
    superseded: false,
    storage_path: `${input.firm_id}/${input.case_id}/${input.id}/${input.filename}`,
    sha256: hash(input.id),
  };
}

