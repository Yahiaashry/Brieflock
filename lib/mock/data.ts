function hash(seed: string) {
  let out = "";
  let x = 2166136261;
  for (let i = 0; i < 64; i += 1) {
    x = Math.imul(x ^ seed.charCodeAt(i % Math.max(seed.length, 1)), 16777619);
    out += (x >>> 0).toString(16).padStart(8, "0");
  }
  return out.slice(0, 64);
}

